<#
.SYNOPSIS
    把 CarSentinel 360 工程发布到 GitHub，触发云端构建，取回两端产物。
    用途：在没有 Mac、没有 Android SDK、没有 git 的 Windows 机器上，一条命令走完「传代码 -> 云端编译 -> 拿包」。

.DESCRIPTION
    全程走 GitHub REST API，不需要安装 git、不需要浏览器拖拽：
      1. 用 PAT 调 /user 验证身份
      2. 建仓库（已存在就复用）
      3. 用 Git Data API 把本地文件逐个做成 blob -> tree -> commit -> 更新 ref
      4. 触发 GitHub Actions 的 workflow_dispatch
      5. 轮询构建状态
      6. 下载全部 artifact，解出 iOS 的 .ipa 和 Android 的 .apk

    PAT 权限要求（classic token）：repo + workflow
    fine-grained token 需要：Contents / Actions / Workflows 三项读写。

.PARAMETER Token
    GitHub Personal Access Token。不传则读环境变量 GITHUB_TOKEN。

.PARAMETER RepoName
    仓库名。留空则自动取 "<project.yml 里的 name>-360"

.PARAMETER Private
    指定则建私有仓库；不加则建公开仓库（公开仓库的 Actions 分钟数不限）

.EXAMPLE
    pwsh -File scripts/publish-github.ps1 -Token $env:GITHUB_TOKEN
#>
[CmdletBinding()]
param(
    [string]$Token = $env:GITHUB_TOKEN,
    [string]$RepoName = "",
    [string]$Description = "CarSentinel 360 - Android car unit + iOS phone app, built in the cloud",
    [string]$Workflow = "build.yml",
    [switch]$Private,
    [switch]$SkipBuild
)

$ErrorActionPreference = "Stop"
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
$ProgressPreference = "SilentlyContinue"

if ([string]::IsNullOrWhiteSpace($Token)) {
    throw "Missing token. Pass -Token <pat> or set env GITHUB_TOKEN."
}

$ApiBase = "https://api.github.com"
$Headers = @{
    "Authorization"        = "Bearer $Token"
    "Accept"               = "application/vnd.github+json"
    "X-GitHub-Api-Version" = "2022-11-28"
    "User-Agent"           = "carsentinel-publisher"
}

function Write-Step($m) { Write-Host ""; Write-Host "=== $m ===" -ForegroundColor Cyan }
function Write-Ok($m)   { Write-Host "  [ok] $m" -ForegroundColor Green }
function Write-Info($m) { Write-Host "  $m" -ForegroundColor DarkGray }

# 所有 JSON 请求统一走这里：强制 UTF-8，避免 PS 5.1 把中文 body 发成 ANSI
function Invoke-Gh {
    param(
        [ValidateSet("Get", "Post", "Patch", "Put", "Delete")][string]$Method,
        [string]$Uri,
        $Body = $null
    )
    $p = @{ Method = $Method; Uri = $Uri; Headers = $Headers }
    if ($null -ne $Body) {
        $json = $Body | ConvertTo-Json -Depth 10 -Compress
        $p["ContentType"] = "application/json; charset=utf-8"
        $p["Body"] = [System.Text.Encoding]::UTF8.GetBytes($json)
    }
    Invoke-RestMethod @p
}

# --------------------------------------------------------------------------
# 0. 定位工程根目录 + 收集文件
# --------------------------------------------------------------------------
Write-Step "Locate project"
$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$Root = if (Test-Path (Join-Path $ScriptDir "..\project.yml")) {
    (Resolve-Path (Join-Path $ScriptDir "..")).Path
} elseif (Test-Path (Join-Path $ScriptDir "..\..\project.yml")) {
    (Resolve-Path (Join-Path $ScriptDir "..\..")).Path
} else {
    throw "project.yml not found next to scripts/"
}
Write-Ok $Root

# 从 project.yml 读 app 名
$specPath = Join-Path $Root "project.yml"
$appName = ""
if (Test-Path $specPath) {
    $m = Select-String -Path $specPath -Pattern '^\s*name:\s*(.+?)\s*$' | Select-Object -First 1
    if ($m) { $appName = $m.Matches[0].Groups[1].Value.Trim('"', "'") }
}
if (-not $appName) { $appName = Split-Path -Leaf $Root }
if ([string]::IsNullOrWhiteSpace($RepoName)) { $RepoName = "$appName-iOS" }
Write-Info "app name  : $appName"
Write-Info "repo name : $RepoName"

$ExcludeDirs  = @("build", "DerivedData", ".git", "$appName.xcodeproj")
$ExcludeFiles = @("Info.plist")   # generated by xcodegen, not committed

$AllFiles = @(Get-ChildItem -Path $Root -Recurse -File -Force | Where-Object {
    $rel = $_.FullName.Substring($Root.Length).TrimStart('\', '/')
    foreach ($p in ($rel -split '[\\/]')) { if ($ExcludeDirs -contains $p) { return $false } }
    if ($ExcludeFiles -contains $_.Name) { return $false }
    return $true
})
Write-Info "files to upload: $($AllFiles.Count)"

# --------------------------------------------------------------------------
# 1. 验证 PAT
# --------------------------------------------------------------------------
Write-Step "Verify token"
$User = Invoke-Gh Get "$ApiBase/user"
Write-Ok "signed in as $($User.login)"

# --------------------------------------------------------------------------
# 2. 建仓库（已存在则复用）
# --------------------------------------------------------------------------
Write-Step "Prepare repo $RepoName"
$Repo = $null
try {
    $Repo = Invoke-Gh Get "$ApiBase/repos/$($User.login)/$RepoName"
    Write-Ok "reusing $($Repo.full_name) (private=$($Repo.private))"
} catch {
    $Repo = Invoke-Gh Post "$ApiBase/user/repos" @{
        name        = $RepoName
        description = $Description
        private     = [bool]$Private
        auto_init   = $true
    }
    Write-Ok "created $($Repo.full_name) (private=$($Repo.private))"
}
$Owner         = $Repo.owner.login
$RepoApi       = "$ApiBase/repos/$Owner/$RepoName"
$DefaultBranch = $Repo.default_branch
Write-Info "default branch: $DefaultBranch"

# --------------------------------------------------------------------------
# 3. 推送文件（blob -> tree -> commit -> ref）
# --------------------------------------------------------------------------
Write-Step "Upload files"

$treeEntries = @()
$idx = 0
foreach ($f in $AllFiles) {
    $idx++
    $rel  = $f.FullName.Substring($Root.Length).TrimStart('\', '/') -replace '\\', '/'
    $b64  = [Convert]::ToBase64String([System.IO.File]::ReadAllBytes($f.FullName))
    $blob = Invoke-Gh Post "$RepoApi/git/blobs" @{ content = $b64; encoding = "base64" }
    $treeEntries += @{ path = $rel; mode = "100644"; type = "blob"; sha = $blob.sha }
    Write-Info ("[{0,2}/{1}] {2}" -f $idx, $AllFiles.Count, $rel)
}

$ref     = Invoke-Gh Get "$RepoApi/git/ref/heads/$DefaultBranch"
$headSha = $ref.object.sha
Write-Info "HEAD before: $headSha"

$tree   = Invoke-Gh Post "$RepoApi/git/trees" @{ tree = $treeEntries }
Write-Ok "tree $($tree.sha)"

try {
    $commit = Invoke-Gh Post "$RepoApi/git/commits" @{
        message = "chore: sync $appName project"
        tree    = $tree.sha
        parents = @($headSha)
    }
} catch {
    if ($_.Exception.Message -match "403|Forbidden|not accessible") {
        Write-Host ""
        Write-Host "  [!!] 403: PAT 缺少 workflow 权限。" -ForegroundColor Red
        Write-Host "       重新生成 token 时，除了 repo 还要勾选 workflow" -ForegroundColor Yellow
        Write-Host "       https://github.com/settings/tokens/new" -ForegroundColor Yellow
    }
    throw
}
Write-Ok "commit $($commit.sha)"

Invoke-Gh Patch "$RepoApi/git/refs/heads/$DefaultBranch" @{ sha = $commit.sha; force = $false } | Out-Null
Write-Ok "pushed to $DefaultBranch"

if ($SkipBuild) { Write-Host ""; Write-Host "--skip-build: done."; exit 0 }

# --------------------------------------------------------------------------
# 4. 触发 workflow（GitHub 索引 workflow 需要几秒，做重试）
# --------------------------------------------------------------------------
Write-Step "Trigger GitHub Actions"
$dispatched = $false
for ($i = 1; $i -le 12; $i++) {
    try {
        Invoke-Gh Post "$RepoApi/actions/workflows/$Workflow/dispatches" @{ ref = $DefaultBranch } | Out-Null
        $dispatched = $true
        Write-Ok "dispatched (attempt $i)"
        break
    } catch {
        Write-Info "attempt $i failed, waiting for GitHub to index the workflow..."
        Start-Sleep -Seconds 10
    }
}
if (-not $dispatched) {
    Write-Host "  [!!] Could not dispatch. Open the Actions tab and click Run workflow manually." -ForegroundColor Yellow
    exit 3
}

# --------------------------------------------------------------------------
# 5. 轮询构建
# --------------------------------------------------------------------------
Write-Step "Waiting for build (first macOS runner can take 5-10 min)"

function Get-LatestRun {
    $runs = Invoke-Gh Get "$RepoApi/actions/runs?branch=$DefaultBranch&per_page=10"
    $wf = $Workflow -replace '\.yml$', ''
    $r = $runs.workflow_runs | Where-Object { $_.path -like "*$wf*" } | Select-Object -First 1
    if (-not $r) { $r = $runs.workflow_runs | Select-Object -First 1 }
    return $r
}

$runId = $null
for ($i = 1; $i -le 30; $i++) {
    Start-Sleep -Seconds 5
    $r = Get-LatestRun
    if ($r) { $runId = $r.id; Write-Ok "run id $runId"; break }
}
if (-not $runId) { throw "could not find the workflow run" }

for ($i = 1; $i -le 200; $i++) {
    $run = Invoke-Gh Get "$RepoApi/actions/runs/$runId"
    Write-Info ("[{0,3}] {1} / {2}" -f $i, $run.status, $run.conclusion)
    if ($run.status -eq "completed") {
        if ($run.conclusion -eq "success") { Write-Ok "build succeeded" }
        else {
            Write-Host "  [!!] build failed: $($run.conclusion)" -ForegroundColor Red
            Write-Host "  logs: $($run.html_url)" -ForegroundColor Yellow
            exit 2
        }
        break
    }
    Start-Sleep -Seconds 10
}

# --------------------------------------------------------------------------
# 6. 下载 artifact（一个 workflow 出两端产物，全部取回来）
# --------------------------------------------------------------------------
Write-Step "Download artifacts"
$artifacts = Invoke-Gh Get "$RepoApi/actions/runs/$runId/artifacts"
if ($artifacts.total_count -lt 1) { throw "no artifact produced" }

New-Item -ItemType Directory -Force -Path (Join-Path $Root "build") | Out-Null
$zipPath = Join-Path $env:TEMP "carsentinel-artifact.zip"
$outDir  = Join-Path $env:TEMP "carsentinel-artifact"
$ipaPath = $null
$apkPath = $null

foreach ($artifact in $artifacts.artifacts) {
    Write-Ok "$($artifact.name) ($([math]::Round($artifact.size_in_bytes/1KB,1)) KB)"
    if (Test-Path $outDir) { Remove-Item $outDir -Recurse -Force }
    Invoke-WebRequest -Uri "$RepoApi/actions/artifacts/$($artifact.id)/zip" -Headers $Headers `
                      -OutFile $zipPath -UseBasicParsing -MaximumRedirection 5
    Expand-Archive -Path $zipPath -DestinationPath $outDir -Force

    if (-not $ipaPath) {
        $ipa = Get-ChildItem -Path $outDir -Recurse -Filter *.ipa | Select-Object -First 1
        if ($ipa) {
            $ipaPath = Join-Path $Root ("build\" + $ipa.Name)
            Copy-Item $ipa.FullName $ipaPath -Force
        }
    }
    if (-not $apkPath) {
        $apk = Get-ChildItem -Path $outDir -Recurse -Filter *.apk | Select-Object -First 1
        if ($apk) {
            $apkPath = Join-Path $Root ("build\" + $apk.Name)
            Copy-Item $apk.FullName $apkPath -Force
        }
    }
    # 构建日志（只有失败时才会有这个 artifact）—— 浏览器连不上 GitHub 时，
    # 这是唯一能把编译错误带回本机的通道
    $logs = @(Get-ChildItem -Path $outDir -Recurse -Filter *.log -ErrorAction SilentlyContinue)
    if ($logs.Count -gt 0) {
        $logDir = Join-Path $Root ("build\logs\" + $artifact.name)
        New-Item -ItemType Directory -Force -Path $logDir | Out-Null
        foreach ($l in $logs) { Copy-Item $l.FullName $logDir -Force }
        Write-Ok "log  : $logDir"
    }

    # 把 Info.plist 的 JSON 副本也带回来（Windows 上没有 plutil，验包要靠它）
    if (-not (Test-Path -LiteralPath (Join-Path $Root "build\Info.json"))) {
        $sidecar = Get-ChildItem -Path $outDir -Recurse -Filter "Info.json" | Select-Object -First 1
        if ($sidecar) {
            Copy-Item $sidecar.FullName (Join-Path $Root "build\Info.json") -Force
            Write-Ok "sidecar: build\Info.json"
        }
    }
}

if (-not $ipaPath -and -not $apkPath) {
    $logHint = ""
    if (Test-Path -LiteralPath (Join-Path $Root "build\logs")) {
        $logHint = " 构建失败，日志在 build\logs\ 下（xcodebuild.log / gradle.log）"
    }
    throw "no .ipa / .apk inside the artifacts.$logHint"
}

Write-Host ""
Write-Host "============================================================" -ForegroundColor Green
Write-Host " ALL DONE" -ForegroundColor Green
if ($ipaPath) {
    Write-Host " ipa (iOS 手机端) : $ipaPath" -ForegroundColor Green
    Write-Host ("   size : {0} MB" -f [math]::Round((Get-Item $ipaPath).Length/1MB, 2)) -ForegroundColor Green
}
if ($apkPath) {
    Write-Host " apk (Android 车机端) : $apkPath" -ForegroundColor Green
    Write-Host ("   size : {0} MB" -f [math]::Round((Get-Item $apkPath).Length/1MB, 2)) -ForegroundColor Green
}
Write-Host " repo : $($Repo.html_url)" -ForegroundColor Green
if (Test-Path -LiteralPath (Join-Path $Root "build\logs")) {
    Write-Host " log  : $(Join-Path $Root 'build\logs')  （构建失败时才有，里面是编译错误）" -ForegroundColor Yellow
}
Write-Host ""
Write-Host " iOS   : 把 ipa 拖进全能签 / ESign -> 选证书重签 -> 下载 -> 装到 iPhone" -ForegroundColor Cyan
Write-Host " Android: 把 apk 传到车机，用文件管理器安装（需允许未知来源）" -ForegroundColor Cyan
Write-Host "============================================================" -ForegroundColor Green
